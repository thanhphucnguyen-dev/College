/** Chỉ định ký tự trong chuỗi (String Operators): +, *, /, **, %, **, **, **, **, **, ** */

let userName = 'NguyenThanhPhuc'
let brandName = 'FullStack Developer'
console.log(userName + ' - ' + brandName) // NguyenThanhPhuc - FullStack Developer
console.log(`${userName} - ${brandName}`) // NguyenThanhPhuc - FullStack Developer




