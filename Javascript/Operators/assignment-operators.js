/* Toán tử gán (Assignment Operators): =, +=, -=, *=, /=, %= */
let x = 10
console.log(x) // 10

x += 5
console.log(x) // tương đương x = x + 5

x -= 4
console.log(x) // tương đương x = x - 4

x *= 3
console.log(x) // tương đương x = x * 3

x /= 2
console.log(x) // tương đương x = x / 2

x %= 3
console.log(x) // tương đương x = x % 3

