/* So sánh (Comparison Operators): ==, ===, !=, !==, >, <, >=, <= */

let x = 10
let y = 5
// let y = '10'
console.log(x === y) // true: x và y cùng một giá trị và cùng kiểu dữ liệu
console.log(x == y) // false: x và y cùng một giá trị và ko cùng kiểu dữ liệu
console.log(x != y)
console.log(x !== y)

console.log(x > y) // true: x lớn hơn y
console.log(x >= y) // true: x lớn hơn hoặc bằng y
console.log(x < y) // false: x nhỏ hơn y
console.log(x <= y) // false: x nhỏ hơn hoặc bằng y


