/* if-else */
let score = 85;

if (score >= 90) {
    console.log('Grade A');
} else if (score >= 75) {
    console.log('Grade B');
} else {
    console.log('Grade C');
}

/* if-else-if */
let score_2 = 85;

if (score_2 >= 90) {
    console.log('Grade A');
} else if (score_2 >= 80) {
    console.log('Grade B');
} else if (score_2 >= 70) {
    console.log('Grade C');
} else {
    console.log('Grade D');
}